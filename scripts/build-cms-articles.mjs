
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  ".."
);

const contentDir = path.join(root, "content", "articles");
const outputFile = path.join(
  root,
  "data",
  "articles",
  "cms-articles.generated.ts"
);

function fail(file, message) {
  throw new Error(
    `[Decap CMS] ${path.relative(root, file)}: ${message}`
  );
}

function isString(value) {
  return typeof value === "string" && value.trim().length > 0;
}

function validateArticle(article, file, filenameSlug) {
  if (
    !article ||
    typeof article !== "object" ||
    Array.isArray(article)
  ) {
    fail(file, "Expected a JSON object.");
  }

  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(filenameSlug)) {
    fail(file, "Filename must use lowercase letters, numbers and hyphens.");
  }

  // Backward compatibility:
  // If an older JSON article already contains a slug,
  // make sure it matches its filename.
  if (article.slug && article.slug !== filenameSlug) {
    fail(file, "Existing article slug does not match its filename.");
  }

  // Generate the article slug from the JSON filename.
  article.slug = filenameSlug;

  for (const key of [
    "title",
    "category",
    "type",
    "readTime",
    "date",
    "excerpt",
    "image"
  ]) {
    if (!isString(article[key])) {
      fail(file, `Missing required field: ${key}`);
    }
  }

  if (!/^\d{4}-\d{2}-\d{2}$/.test(article.date)) {
    fail(file, "date must use YYYY-MM-DD.");
  }

  if (
    article.updatedDate &&
    !/^\d{4}-\d{2}-\d{2}$/.test(article.updatedDate)
  ) {
    fail(file, "updatedDate must use YYYY-MM-DD.");
  }

  if (
    !article.content ||
    !isString(article.content.introduction)
  ) {
    fail(file, "content.introduction is required.");
  }

  if (
    !Array.isArray(article.content.sections) ||
    article.content.sections.length === 0
  ) {
    fail(file, "Add at least one content section.");
  }

  article.content.sections.forEach((section, index) => {
    if (!isString(section.heading)) {
      fail(file, `Section ${index + 1} needs a heading.`);
    }

    if (
      !Array.isArray(section.paragraphs) ||
      section.paragraphs.length === 0 ||
      !section.paragraphs.every(isString)
    ) {
      fail(
        file,
        `Section ${index + 1} needs at least one paragraph.`
      );
    }

    if (
      section.bullets !== undefined &&
      (
        !Array.isArray(section.bullets) ||
        !section.bullets.every(isString)
      )
    ) {
      fail(file, `Section ${index + 1} has invalid bullets.`);
    }
  });

  if (
    article.faqs !== undefined &&
    (
      !Array.isArray(article.faqs) ||
      !article.faqs.every(
        (faq) => isString(faq.question) && isString(faq.answer)
      )
    )
  ) {
    fail(file, "Each FAQ needs a question and answer.");
  }

  if (
    article.tags !== undefined &&
    (
      !Array.isArray(article.tags) ||
      !article.tags.every(isString)
    )
  ) {
    fail(file, "tags must be an array of non-empty strings.");
  }

  if (
    article.sources !== undefined &&
    (
      !Array.isArray(article.sources) ||
      !article.sources.every(isString)
    )
  ) {
    fail(file, "sources must be an array of non-empty strings.");
  }
}

fs.mkdirSync(contentDir, { recursive: true });

fs.mkdirSync(path.dirname(outputFile), {
  recursive: true
});

const files = fs
  .readdirSync(contentDir)
  .filter((name) => name.toLowerCase().endsWith(".json"))
  .sort();

const articles = [];
const seenSlugs = new Set();

for (const name of files) {
  const file = path.join(contentDir, name);
  const filenameSlug = path.basename(name, path.extname(name));

  let article;

  try {
    article = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    fail(file, `Invalid JSON (${error.message}).`);
  }

  validateArticle(article, file, filenameSlug);

  if (seenSlugs.has(filenameSlug)) {
    fail(file, `Duplicate article slug: ${filenameSlug}`);
  }

  seenSlugs.add(filenameSlug);

  articles.push(article);
}

const source = `// AUTO-GENERATED by scripts/build-cms-articles.mjs. Do not edit by hand.
import type { Article } from "./types";

export const cmsArticles: Article[] = ${JSON.stringify(
  articles,
  null,
  2
)};
`;

fs.writeFileSync(outputFile, source, "utf8");

console.log(
  `[Decap CMS] Loaded ${articles.length} CMS article(s).`
);
